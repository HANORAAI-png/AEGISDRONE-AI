export function generateInitialObjects(scenario: ScenarioConfig): DroneObject[] {
  const count = scenario.objectCount || 3;
  const objects: DroneObject[] = [];
  const prefixes = ['A', 'B', 'C', 'D', 'E', 'F'];

  for (let i = 0; i < count; i++) {
    const angle = (i * (360 / count) + 35 + Math.random() * 30) * (Math.PI / 180);
    const startDistKm = 1.7 + Math.random() * 0.5; // ~1.7 - 2.2 km from center
    const x = Math.cos(angle) * startDistKm * 95; // canvas pixel offset scale
    const y = Math.sin(angle) * startDistKm * 95;

    // Head towards or near center
    const targetAngle = Math.atan2(-y, -x) + (Math.random() - 0.5) * 0.6;
    const headingDeg = Math.round(((targetAngle * 180) / Math.PI + 360) % 360);

    const isHighThreat = i === 0; // Ensure primary interesting target
    const id = `OBJECT ${prefixes[i] || 'X'}-${10 + Math.floor(Math.random() * 89)}`;

    objects.push({
      id,
      x,
      y,
      altitude: Math.round(90 + Math.random() * 140), // 90m to 230m
      speed: Math.round(14 + Math.random() * 12), // 14m/s to 26m/s
      heading: headingDeg,
      distance: Number(startDistKm.toFixed(2)),
      trajectory: isHighThreat ? 'Inbound' : i % 2 === 0 ? 'Tangential' : 'Inbound',
      classification: isHighThreat ? 'Multi-Rotor Drone' : i % 2 === 0 ? 'Micro-UAV' : 'Fixed-Wing Model',
      detectionConfidence: 68 + Math.floor(Math.random() * 24),
      classificationConfidence: 55 + Math.floor(Math.random() * 30),
      status: i === 0 ? 'TRACKED' : 'DETECTED',
      threatLevel: isHighThreat ? 'HIGH' : i % 2 === 0 ? 'LOW' : 'MEDIUM',
      threatScore: isHighThreat ? 88 : i % 2 === 0 ? 32 : 65,
      inRestrictedZone: false,
      inWarningZone: false,
      anomalyFlags: isHighThreat
        ? ['Inbound vector directly toward protected asset', 'Zero ADS-B transponder', 'Low radar cross section']
        : ['Tangential transit flight path'],
      history: [{ x, y, time: Date.now() }],
    });
  }

  return objects;
}
